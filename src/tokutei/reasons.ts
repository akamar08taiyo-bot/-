/** 細目の分からない入浴補助用具・腰掛便座：細目ごとの1つめの文例 */
function firstOfSubs(category: string): string[] {
  const c = CATEGORIES.find((x) => x.name === category);
  return c ? c.subs.map((s) => BY_SUB[s]?.[0]).filter((x): x is string => !!x) : [];
}

/**
 * この種目（細目）の文例。細目が空なら商品名から細目を見る（手で入れた商品。種目の欄は種目だけを選ぶので）。
 * 細目の文例がなければ種目の文例
 */
export function reasonExamples(category: string, sub: string, name = ''): string[] {
  const g = !sub && name ? guessCategory(name) : null;
  const s = sub || (g && g.category === category ? g.sub : '');
  return BY_SUB[s] ?? BY_CATEGORY[category] ?? firstOfSubs(category);
}

/** 前に同じ種目（細目）で書いた理由（新しい順・同じ文は1つ。文例と同じものは除く） */
export function pastReasons(sales: Sale[], category: string, sub: string, exceptSaleId = ''): string[] {
  if (!category) return [];
  const examples = new Set(reasonExamples(category, sub));
  const seen = new Set<string>();
  const out: string[] = [];
  for (const s of [...sales].sort((a, b) => b.updatedAt - a.updatedAt)) {
    if (s.id === exceptSaleId) continue;
    for (const i of s.items) {
      const r = i.reason.trim();
      if (!r || i.category !== category || i.sub !== sub || examples.has(r) || seen.has(r)) continue;
      seen.add(r);
      out.push(r);
    }
  }
  return out.slice(0, 5);
}
