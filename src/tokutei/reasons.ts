/** この種目（細目）の文例 */
export function reasonExamples(category: string, sub: string): string[] {
  return BY_SUB[sub] ?? BY_CATEGORY[category] ?? [];
}

/** 前に同じ種目（細目）で書いた理由（新しい順・同じ文は1つ。文例と同じものは除く） */
export function pastReasons(sales: Sale[], category: string, sub: string, exceptSaleId = ''): string[] {
  if (!category) return [];
  const examples = new Set(reasonExamples(category, sub));
  const seen = new Set<string>();
  const out: string[] = [];
  for (const s of [...sales].sort((a, b) => b.updatedAt - a.updatedAt)) {
    if (s.id === exceptSaleId) continue;
    for (const i of s.items) {
      const r = i.reason.trim();
      if (!r || i.category !== category || i.sub !== sub || examples.has(r) || seen.has(r)) continue;
      seen.add(r);
      out.push(r);
    }
  }
  return out.slice(0, 5);
}
