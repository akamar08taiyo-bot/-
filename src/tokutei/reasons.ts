/** 細目の分からない入浴補助用具・腰掛便座で並べる順（よく使うものから） */
const SUB_ORDER: Record<string, string[]> = {
  入浴補助用具: ['入浴用いす', '浴槽内いす', '浴槽用手すり', '入浴台', '浴室内すのこ', '浴槽内すのこ', '入浴用介助ベルト'],
  腰掛便座: ['移動できる便器（ポータブルトイレ）', '和式便器を腰掛式にするもの', '洋式便器の高さを補うもの', '立ち上がりを補助するもの'],
};

/** 種目・細目の文例。細目の文例がなければ種目の文例、種目の文例もなければ（細目の分からない入浴補助用具・腰掛便座）細目ごとの文例を全部 */
function groupsOf(category: string, sub: string): ReasonGroup[] {
  if (BY_SUB[sub]) return BY_SUB[sub];
  if (BY_CATEGORY[category]) return [{label: category, texts: BY_CATEGORY[category]}];
  const subs = SUB_ORDER[category] ?? CATEGORIES.find((x) => x.name === category)?.subs ?? [];
  return subs.flatMap((x) => BY_SUB[x] ?? []);
}

/**
 * この種目（細目）の文例（見出しごと）。**選んだ種目の文例だけ**を出す（ユーザーの指示「歩行補助杖を選択したのに、シャワーチェアの文例がでる。腰掛便座の文例か」2026-10-26。
 * 前は商品名から別の種目と分かるとき、商品名の用具の文例を先に出していた）。細目が空なら、商品名から推した細目がその種目のものなら使う（手で入れた商品。種目の欄は種目だけを選ぶので）。
 * 細目がその種目のものでなければ（前の種目の細目が残っていた）使わない。種目を選んでいなければ、商品名から推した種目の文例
 */
export function reasonExamples(category: string, sub: string, name = ''): ReasonGroup[] {
  const subs = (c: string) => CATEGORIES.find((x) => x.name === c)?.subs ?? [];
  const g = name && (!sub || !category) ? guessCategory(name) : null;
  if (!category) return g?.category ? groupsOf(g.category, g.sub) : [];
  const own = sub && (subs(category).includes(sub) || !CATEGORIES.some((x) => x.name === category)) ? sub : '';
  return groupsOf(category, own || (g && g.category === category ? g.sub : ''));
}

/** 前に同じ種目（細目）で書いた理由（新しい順・同じ文は1つ。文例と同じものは除く） */
export function pastReasons(sales: Sale[], category: string, sub: string, exceptSaleId = ''): string[] {
  if (!category) return [];
  const examples = new Set(reasonExamples(category, sub).flatMap((x) => x.texts));
  const seen = new Set<string>();
  const out: string[] = [];
  for (const s of [...sales].sort((a, b) => b.updatedAt - a.updatedAt)) {
    if (s.id === exceptSaleId) continue;
    for (const i of s.items) {
      const r = i.reason.trim();
      if (!r || i.category !== category || i.sub !== sub || examples.has(r) || seen.has(r)) continue;
      seen.add(r);
      out.push(r);
    }
  }
  return out.slice(0, 5);
}
