// 種目（特定福祉用具の種類）の自動判定。商品名（と価格表の分類の列）から、申請書・見積書に書く種目と細目を決める。
// 決まらない商品は空のまま（取り込みの確認・商品マスタで選ぶ）。手で選んだ種目は、価格表を取り込み直しても変えない。
// 種目の範囲は自治体の資料（北九州市・和歌山市など）で確かめたもの。2024年4月から固定用スロープ・歩行器・歩行補助つえが加わった。

/**
 * 種目と細目（画面で選ぶときの候補。名前は申請書に書く名前）。並びはよく出る順（ユーザーの指示「一番上に入浴補助用具、次に腰掛け便座、
 * その後に歩行補助杖、歩行器、固定用スロープ。他はどの順番でもいい」2026-10-26）。種目の欄・商品マスタの絞り込みと並びもこの順
 */
export const CATEGORIES: {name: string; subs: string[]}[] = [
  {name: '入浴補助用具', subs: ['入浴用いす', '浴槽用手すり', '浴槽内いす', '入浴台', '浴室内すのこ', '浴槽内すのこ', '入浴用介助ベルト']},
  {name: '腰掛便座', subs: ['和式便器を腰掛式にするもの', '洋式便器の高さを補うもの', '立ち上がりを補助するもの', '移動できる便器（ポータブルトイレ）']},
  {name: '歩行補助つえ', subs: ['多点杖', 'ロフストランド・クラッチ', 'カナディアン・クラッチ', 'プラットホームクラッチ']},
  {name: '歩行器', subs: []},
  {name: '固定用スロープ', subs: []},
  {name: '自動排泄処理装置の交換可能部品', subs: []},
  {name: '排泄予測支援機器', subs: []},
  {name: '簡易浴槽', subs: []},
  {name: '移動用リフトのつり具の部分', subs: []},
];

/**
 * 消費税のかからない種目（身体障害者用物品：歩行器・歩行補助つえ（多点杖・クラッチ）。介援隊カタログでも金額の横に「非課税」）。
 * ユーザーの指示「歩行器（ピックアップ）や四点杖は非課税。カタログの横にも記載してある。しっかりと全ての商品で認識する」2026-11-03。
 * 介護保険で買える歩行器（固定式・交互式）・歩行補助つえは、どれも非課税
 */
export const TAX_FREE_CATEGORIES = ['歩行器', '歩行補助つえ'];
export const taxFreeCategory = (category: string) => TAX_FREE_CATEGORIES.includes(category);

/** category が空なら決まらなかった。warn は対象外と分かったときの理由（画面で知らせる） */
export type CategoryGuess = {category: string; sub: string; warn: string};

const none = (warn = ''): CategoryGuess => ({category: '', sub: '', warn});
const hit = (category: string, sub = ''): CategoryGuess => ({category, sub, warn: ''});

const norm = (s: string) => (s || '').normalize('NFKC').replace(/\s+/g, ' ').trim();

// 本体ではなく、消耗品・付属品（申請の対象にならない）
const ACCESSORY = /(消臭|脱臭|防臭)(剤|液)|処理袋|凝固剤|杖先ゴム|替えゴム|交換用(ゴム|キャップ|座面)|(専用|用)(バケツ|処理袋|カバー|消臭剤)|(バケツ|カバー)のみ|袋止め|専用フィルム|カートリッジ/;

// 介援隊カタログの商品名で、名前に「シャワーチェア」「トイレ」がなくても種類の分かるもの（2026-11-01 ユーザーの指示
// 「シャワーキャリーはシャワーチェア、ラップポンは腰掛便座など、カタログ一覧の全ての項目でわかるようにする」。カタログ p.40〜51・151〜154・172〜179 の名前で確かめた）
/** シャワーキャリー（キャスター付きの入浴用いす）。入浴用いすの1つ */
const SHOWER_CARRIER =
  /シャワーキャリー|(入浴|浴用|シャワー)(用)?キャリー|シャワー用車いす|入浴.*車いす|シャワーラク|シャトレチェア|くるくるチェア|シャワースカール|楽チル|はいらーく|はいねーる|ハイベル|安楽キャリー/;
/** ポータブルトイレ（名前に「トイレ」のないものも） */
const PORTABLE_TOILET =
  /ポータブルトイレ|家具調(スマート)?トイレ|水洗(式)?ポータブル|ベッドサイド(水洗)?トイレ|トイレチェア|ラップポン|さわやか(チェア|あさひ)|たため[〜~ー～]?る|あらえ[〜~ー～]?る|きらく|ジャスピタ|楽立|トワレット|座楽|セレクト[RS]|FX-?(30|CP)|ちびくま|軽[〜~ー～]?いトイレ/i;
/** 多点杖（名前に「杖」のないものも：楽スマ スリーベース・カルモトリプル・エルビスクワド など） */
// 「四脚杖」「多脚杖」「クアッドケイン」「トライポッド杖」も多点杖（前は T字杖とみて対象外にしていた。2026-11-08 のデバッグ）
const MULTI_CANE = /多点|[34３４三四]点|[34３４]ポイント|多脚|[34３４三四]脚|トリプル|スリーベース|クワド|クオッド|クアッド|クァッド|トライポッド|テトラポッド|テトラケイン/;
/** 車輪・キャスター・ブレーキが「ない」ことを書いた所（「キャスター付属なし」「ブレーキ無し」は固定式の歩行器。前は車輪ありとみていた） */
const NO_WHEELS = /(キャスター|車輪|ブレーキ)\s*(付属|付き|つき|付)?\s*(なし|無し|ナシ|無)/g;
/** 車輪のある歩行器（歩行車）か（「〜なし」は除いて見る） */
export const wheeled = (s: string) => WHEELED.test(s.replace(NO_WHEELS, ''));
/** 車輪・キャスターのある歩行器（歩行車・シルバーカー）の言葉。カタログの説明の文（「前脚のスイングキャスター」「ハンドブレーキ」）にも使う */
export const WHEELED = /歩行車|キャスター|車輪|輪付|前輪|後輪|固定輪|ブレーキ|ロレータ|シルバーカー|ショッピング/;
/** 介護保険の対象外と分かるもの（理由を出す）。すべり止めマット・入浴用のクッション・リフト */
const NOT_COVERED: [RegExp, string][] = [
  [/(すべり|滑り)止め.*(マット|シート)|マット|まっと|ピタットシート/, 'すべり止めマットは介護保険の対象外です'],
  [/クッション|ピロー|座ぶとん|手袋/, '入浴用のクッション・小物は介護保険の対象外です'],
  [/バスリフト|入浴(補助)?リフト|介護リフト|移乗サポートロボット|つるべー/, 'リフトの本体は貸与の品目です（購入の対象外）'],
];

/**
 * 種目と細目を推測する。name は商品名、hint は価格表の「種目」「分類」の列の文字（なければ空）。
 * 分類の列に種目の名前が入っていればそれを先に使う（細目は商品名からも探す）
 */
export function guessCategory(name: string, hint = ''): CategoryGuess {
  const h = norm(hint);
  if (h) {
    const c = CATEGORIES.find((x) => h.includes(x.name));
    // 分類が「歩行器」「歩行補助つえ」でも、商品名から対象外と分かるもの（歩行車・シルバーカー・T字杖・松葉づえ）は対象外（前は分類のとおり対象・非課税にしていた）
    if (c && taxFreeCategory(c.name)) {
      const g = byName(norm(name));
      if (!g.category && g.warn) return g;
    }
    if (c) {
      const sub = c.subs.find((x) => h.includes(x)) ?? (byName(norm(name)).category === c.name ? byName(norm(name)).sub : '');
      return hit(c.name, sub);
    }
    const g = byName(h); // 分類の列が「シャワーチェア」「浴槽台」のような細目の名前のとき
    if (g.category) return g;
  }
  return byName(norm(name));
}

function byName(s: string): CategoryGuess {
  if (!s) return none();
  if (ACCESSORY.test(s)) return none('消耗品・付属品は申請の対象になりません');

  // 入浴補助用具の細目の名前がそのまま入っているとき
  const bath = CATEGORIES.find((c) => c.name === '入浴補助用具')!;
  const literal = bath.subs.find((x) => s.includes(x));
  if (literal) return hit('入浴補助用具', literal);

  // 自動排泄処理装置：交換できる部品（尿や便の通り道）だけが対象。本体は貸与
  if (/自動排泄|排泄処理装置|ヒューマニー|スカットクリーン|マインレット/.test(s)) {
    return /レシーバー|チューブ|タンク|カップ|部品/.test(s) ? hit('自動排泄処理装置の交換可能部品') : none('自動排泄処理装置の本体は貸与の品目です');
  }
  if (/排泄予測|排尿予測|dfree/i.test(s)) return hit('排泄予測支援機器');
  if (/簡易浴槽|ポータブル浴槽|空気式浴槽|折りたたみ浴槽/.test(s)) return hit('簡易浴槽');
  if (/つり具|吊り具|吊具|スリング/.test(s)) return hit('移動用リフトのつり具の部分');

  // 入浴補助用具（見分けやすい順に見る）。ベルトはキャリーより先（「新・入浴用キャリーベルト」）
  if (/入浴.*(介助)?ベルト|介助ベルト.*入浴|たすけ帯.*入浴|入浴.*たすけ帯/.test(s)) return hit('入浴補助用具', '入浴用介助ベルト');
  if (SHOWER_CARRIER.test(s)) return hit('入浴補助用具', '入浴用いす');
  if (/浴槽(内|用)すのこ/.test(s)) return hit('入浴補助用具', '浴槽内すのこ');
  if (/すのこ/.test(s)) return hit('入浴補助用具', '浴室内すのこ');
  // 入浴グリップ（パナソニック ユクリア）も浴槽のふちに付ける手すり（カタログ p.45）
  // マスカット ポールタイプ（DIPPERホクメイ）は浴槽のそばに立てる手すり（カタログ p.46）
  if (/浴槽(用)?(手すり|手摺|グリップ)|バスグリップ|バスタブグリップ|入浴グリップ|マスカット/.test(s)) return hit('入浴補助用具', '浴槽用手すり');
  if (/浴槽台|浴槽内(いす|イス|椅子|チェア)|バスステップ/.test(s)) return hit('入浴補助用具', '浴槽内いす');
  if (/バスボード|浴槽ボード|移乗台|バスベンリー|アクアムーブ/.test(s)) return hit('入浴補助用具', '入浴台');
  if (/シャワー(チェア|ベンチ|いす|イス|椅子)|入浴用(いす|イス|椅子|チェア)|バスチェア|風呂(いす|イス|椅子)/.test(s)) return hit('入浴補助用具', '入浴用いす');

  // 腰掛便座
  if (/補高便座|便座(を)?補高/.test(s)) return hit('腰掛便座', '洋式便器の高さを補うもの');
  if (/昇降便座|便座昇降|立ち上がり補助便座/.test(s)) return hit('腰掛便座', '立ち上がりを補助するもの');
  if (/据置(式)?便座|和式(便器)?.*(腰掛|洋式)|サニタリエース/.test(s)) return hit('腰掛便座', '和式便器を腰掛式にするもの');
  if (PORTABLE_TOILET.test(s)) return hit('腰掛便座', '移動できる便器（ポータブルトイレ）');
  if (/腰掛便座/.test(s)) return hit('腰掛便座');

  // 対象外と分かるもの（マット・クッション・リフト）。対象の種類（浴槽台の「ソフトクッションタイプ」など）を先に見てから
  for (const [re, why] of NOT_COVERED) if (re.test(s)) return none(why);

  // 2024年4月からの3つ（貸与と販売を選べる）。対象外のもの（持ち運ぶスロープ・歩行車・T字杖）は理由を返す
  if (/スロープ/.test(s)) {
    return /携帯|ポータブル|可搬|折りたたみ|折り畳み|車載|伸縮/.test(s) ? none('持ち運ぶスロープは対象外（固定用スロープだけ）') : hit('固定用スロープ');
  }
  // 歩行器：選択制の対象は、脚がすべて杖先ゴムの固定式・交互式だけ。車輪・キャスターのある歩行車は対象外（厚労省「選択制の対象とする種目に関する解釈」）。
  // スライドフィット・ミニフィット（ユーバ産業）も歩行器（カタログ p.136）
  if (/歩行器|ウォーカー|スライドフィット|ミニフィット/.test(s)) {
    return wheeled(s) ? none('車輪のある歩行車は対象外') : hit('歩行器');
  }
  // 歩行車・シルバーカーは名前に「歩行器」がなくても対象外（価格表の分類が「歩行器」のときに、ここで止める）
  if (wheeled(s) && /歩行|ロレータ|シルバーカー/.test(s)) return none('車輪のある歩行車は対象外');
  if (/杖|つえ|ステッキ|クラッチ|ケイン/.test(s) || MULTI_CANE.test(s)) {
    // エルボークラッチはロフストランド・クラッチの別の呼び名
    if (/ロフストランド|エルボー\s*・?\s*クラッチ/.test(s)) return hit('歩行補助つえ', 'ロフストランド・クラッチ');
    if (/カナディアン/.test(s)) return hit('歩行補助つえ', 'カナディアン・クラッチ');
    if (/プラットホーム|プラットフォーム/.test(s)) return hit('歩行補助つえ', 'プラットホームクラッチ');
    if (MULTI_CANE.test(s)) return hit('歩行補助つえ', '多点杖');
    if (/松葉/.test(s)) return none('松葉づえは対象外');
    return none('T字杖など1本の杖は対象外（多点杖・ロフストランドなどだけ）');
  }
  return none();
}

/**
 * 細目（品目）のふだんの呼び方（画面のボタン・商品の一覧の印）。シャワーキャリーも入浴用いすなので「シャワーチェア」の中に入る
 * （ユーザーの指示「シャワーキャリーはシャワーチェア…シャワーチェアを選んだら、シャワーチェアの一覧のみ」2026-11-01）
 */
const SUB_SHORT: Record<string, string> = {
  入浴用いす: 'シャワーチェア',
  浴槽内いす: '浴槽台',
  浴槽用手すり: '浴槽手すり',
  入浴台: 'バスボード',
  入浴用介助ベルト: '入浴用介助ベルト',
  '移動できる便器（ポータブルトイレ）': 'ポータブルトイレ',
  和式便器を腰掛式にするもの: '据置式便座',
  洋式便器の高さを補うもの: '補高便座',
  立ち上がりを補助するもの: '昇降便座',
};
/** 細目を、種目の候補（CATEGORIES）の順に並べる（品目のボタンの並び） */
export const sortSubs = (subs: string[]) => {
  const order = CATEGORIES.flatMap((c) => c.subs);
  const at = (x: string) => (order.indexOf(x) < 0 ? order.length : order.indexOf(x));
  return [...subs].sort((a, b) => at(a) - at(b));
};
/** 品目の呼び方（細目がなければ種目） */
export const subShort = (sub: string, category = '') => (sub ? (SUB_SHORT[sub] ?? sub) : category);

/** 種目と細目を1つの文字にする（画面で選ぶとき）：「入浴補助用具（入浴用いす）」 */
export function categoryLabel(category: string, sub: string): string {
  if (!category) return '';
  return sub ? `${category}（${sub}）` : category;
}

/**
 * 書類に書く種目は種目だけ（「入浴補助用具」「腰掛便座」）。ユーザーの指示「リストはシンプルに、入浴補助用具、腰掛便座などシンプルで良い」（2026-10-26）で、
 * 前の「入浴補助用具（入浴用いす）」の細目を外した（選ぶ欄も種目だけ。細目は理由の頭の呼び名に残す）
 */
export function docLabel(category: string, _sub: string): string {
  return category;
}

