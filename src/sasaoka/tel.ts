const AREA2 = new Set(['03', '06']);

/** 打った電話番号を、数字だけで打ち終わっていればハイフン付きに。そうでなければ打ったまま */
export function telWithHyphens(v: string): string {
  const t = v.normalize('NFKC').trim();
  if (!/^0\d+$/.test(t)) return v;
  // フリーダイヤルなど（0120・0570 は 10けた 4-3-3、0800 は 11けた 4-3-4。0800 は携帯の 080 より先に見る）
  if (/^0(120|570)/.test(t)) return t.length === 10 ? `${t.slice(0, 4)}-${t.slice(4, 7)}-${t.slice(7)}` : v;
  if (/^0800/.test(t)) return t.length === 11 ? `${t.slice(0, 4)}-${t.slice(4, 7)}-${t.slice(7)}` : v;
  // 携帯・PHS・IP 電話・M2M（11けた：3-4-4）
  if (/^0[5-9]0/.test(t) || /^020/.test(t)) return t.length === 11 ? `${t.slice(0, 3)}-${t.slice(3, 7)}-${t.slice(7)}` : v;
  if (t.length !== 10) return v;
  const area = AREA4.has(t.slice(0, 4)) ? 4 : AREA3.has(t.slice(0, 3)) ? 3 : AREA2.has(t.slice(0, 2)) ? 2 : 0;
  if (!area) return v;
  return `${t.slice(0, area)}-${t.slice(area, 6)}-${t.slice(6)}`;
}
